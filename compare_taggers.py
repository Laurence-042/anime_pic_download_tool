#!/usr/bin/env python
"""
Tagger Comparison Tool - Compare tags from different taggers

This script compares tags generated by different tagger models (WD14, ML-Danbooru, Camie)
and shows the differences between them.

Usage:
    # Compare two taggers on a single image
    python compare_taggers.py image.png --tagger1 wd14 --tagger2 camie
    
    # Compare with custom thresholds
    python compare_taggers.py image.png --tagger1 wd14 --tagger2 mldanbooru --threshold 0.4
    
    # Compare on a directory
    python compare_taggers.py ./download --recursive --tagger1 wd14 --tagger2 camie
    
    # Export comparison to JSON
    python compare_taggers.py image.png --tagger1 wd14 --tagger2 camie --export comparison.json

Available taggers:
    - wd14: WD14 EVA02-Large model (9k tags)
    - mldanbooru: ML-Danbooru Caformer model (12,547 tags)
    - camie: Camie model (70,000+ tags)
"""

